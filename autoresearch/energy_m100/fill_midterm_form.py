def set_cell(cell, text, size=12, bold=False):
    # 清空再按行写入,保留字号
    cell.text = ""
    lines = text.split("\n")
    p0 = cell.paragraphs[0]
    for i, ln in enumerate(lines):
        p = p0 if i == 0 else cell.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0.74) if ln.startswith(("本课题","以 ","将 ","为 ","课题核心","真机功率")) or ln[:2] in ("①","②","③","（") else None
        p.paragraph_format.line_spacing = 1.4
        r = p.add_run(ln); r.font.size = Pt(size); r.font.bold = bold
        r.font.name = "宋体"
        from docx.oxml.ns import qn
        r._element.rPr.rFonts.set(qn('w:eastAsia'), "宋体")


